  /// 汉字转拼音
  ///
  /// [text] 中文文本
  /// [separator] 分隔符
  /// [capitalize] 是否首字母大写
  /// [keepToneNumbers] 是否保留音调数字
  /// [initialOnly] 是否仅返回首字母
  /// 返回拼音字符串
  static String convert(
    String text, {
    String separator = ' ',
    bool capitalize = false,
    bool keepToneNumbers = true,
    bool initialOnly = false,
  }) {
    if (text.isEmpty) return '';

    final parts = <String>[];

    for (int i = 0; i < text.length; i++) {
      final char = text[i];
      final rawPinyin = _pinyinMap[char];

      if (rawPinyin != null) {
        String pinyin = rawPinyin;
        if (!keepToneNumbers) {
          pinyin = _removeToneNumber(pinyin);
        }
        if (initialOnly) {
          parts.add(pinyin[0].toUpperCase());
        } else if (capitalize) {
          parts.add('${pinyin[0].toUpperCase()}${pinyin.substring(1)}');
        } else {
          parts.add(pinyin);
        }
      } else {
        parts.add(char);
      }
    }

    return parts.join(separator);
  }

  /// 获取拼音首字母缩写
  ///
  /// [text] 中文文本
  /// 返回大写首字母缩写，如 "中国" → "ZG"
  static String getInitials(String text) {
    return convert(text, separator: '', keepToneNumbers: false, initialOnly: true);
  }

  /// 判断是否为汉字
  static bool isChinese(String char) {
    if (char.isEmpty) return false;
    final code = char.codeUnitAt(0);
    return code >= 0x4E00 && code <= 0x9FA5;
  }

  /// 统计汉字数量
  static int countChineseChars(String text) {
    int count = 0;
    for (final char in text.split('')) {
      if (isChinese(char)) count++;
    }
    return count;
  }

  /// 检查字符串是否包含汉字
  static bool hasChinese(String text) {
    return text.split('').any(isChinese);
  }

  /// 移除拼音中的音调数字
  ///
  /// [pinyin] 带音调的拼音，如 "hao3"
  /// 返回无声调拼音，如 "hao"
  static String _removeToneNumber(String pinyin) {
    if (pinyin.isEmpty) return pinyin;
    final lastChar = pinyin[pinyin.length - 1];
    if (lastChar.codeUnitAt(0) >= 0x31 && lastChar.codeUnitAt(0) <= 0x35) {
      return pinyin.substring(0, pinyin.length - 1);
    }
    return pinyin;
  }
